package br.com.erp.anuncio;

/** Lugares da loja onde cabe um anúncio. */
public enum PosicaoAnuncio {
    /** Página inicial, logo abaixo do destaque principal. */
    HOME_TOPO,
    /** Página inicial, entre as fileiras de produtos. */
    HOME_MEIO,
    /** Listas e categorias, no meio da grade de produtos. */
    LISTA,
    /** Página do produto, abaixo das ofertas. */
    PRODUTO,
    /** Todas as páginas, logo acima do rodapé. */
    RODAPE
}
